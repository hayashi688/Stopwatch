CREATE TABLE IF NOT EXISTS work_groups (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE CHECK (length(trim(name)) > 0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS work_items (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 group_id BIGINT REFERENCES work_groups(id) ON DELETE SET NULL,
 name VARCHAR(200) NOT NULL CHECK (length(trim(name)) > 0),
 is_archived BOOLEAN NOT NULL DEFAULT false,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS item_name_group ON work_items(group_id,name) WHERE group_id IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS item_name_ungrouped ON work_items(name) WHERE group_id IS NULL;
CREATE TABLE IF NOT EXISTS timer_sessions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 work_item_id BIGINT NOT NULL REFERENCES work_items(id),
 started_at TIMESTAMPTZ NOT NULL, ended_at TIMESTAMPTZ,
 status VARCHAR(20) NOT NULL CHECK (status IN ('RUNNING','STOPPED','CANCELED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK ((status='RUNNING' AND ended_at IS NULL) OR (status<>'RUNNING' AND ended_at>=started_at))
);
CREATE UNIQUE INDEX IF NOT EXISTS only_one_running ON timer_sessions((status)) WHERE status='RUNNING';
CREATE TABLE IF NOT EXISTS work_records (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 work_item_id BIGINT NOT NULL REFERENCES work_items(id),
 timer_session_id BIGINT UNIQUE REFERENCES timer_sessions(id),
 record_type VARCHAR(20) NOT NULL CHECK (record_type IN ('TIMER','MANUAL')),
 work_date DATE, started_at TIMESTAMPTZ, ended_at TIMESTAMPTZ,
 duration_ms BIGINT NOT NULL CHECK (duration_ms>0), memo TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK ((record_type='TIMER' AND started_at IS NOT NULL AND ended_at>started_at AND work_date IS NULL AND timer_session_id IS NOT NULL AND duration_ms=(extract(epoch FROM (ended_at-started_at))*1000)::bigint)
 OR (record_type='MANUAL' AND work_date IS NOT NULL AND started_at IS NULL AND ended_at IS NULL AND timer_session_id IS NULL AND duration_ms<=86400000))
);
CREATE INDEX IF NOT EXISTS record_date ON work_records(work_date);
CREATE INDEX IF NOT EXISTS record_interval ON work_records(started_at,ended_at);
